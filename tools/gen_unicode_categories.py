#!/usr/bin/env python3
"""Generate src/xsd/unicode_categories.zig from Unicode data files.

Usage: gen_unicode_categories.py [DATA_DIR] [OUTPUT]

DATA_DIR defaults to /usr/share/unicode and must contain UnicodeData.txt and
Blocks.txt (Unicode 15.0 or later). The generated file is checked in, so the
build never needs these files.
"""

import os
import sys

CATEGORY_CODES = [
    "Lu", "Ll", "Lt", "Lm", "Lo",
    "Mn", "Mc", "Me",
    "Nd", "Nl", "No",
    "Pc", "Pd", "Ps", "Pe", "Pi", "Pf", "Po",
    "Sm", "Sc", "Sk", "So",
    "Zs", "Zl", "Zp",
    "Cc", "Cf", "Co", "Cs", "Cn",
]

# Historical block names kept for compatibility with libxml2 and XSD 1.0.
BLOCK_ALIASES = {
    "Greek": "GreekandCoptic",
    "CyrillicSupplementary": "CyrillicSupplement",
    "CombiningMarksforSymbols": "CombiningDiacriticalMarksforSymbols",
    "PrivateUse": "PrivateUseArea",
}


def parse_unicode_data(path):
    """Return sorted (start, end, category) runs of assigned codepoints."""
    entries = []
    pending_start = None
    with open(path, encoding="utf-8") as handle:
        for line in handle:
            fields = line.rstrip("\n").split(";")
            if len(fields) < 3:
                continue
            codepoint = int(fields[0], 16)
            name = fields[1]
            category = fields[2]
            if name.endswith(", First>"):
                pending_start = codepoint
                pending_category = category
                continue
            if name.endswith(", Last>"):
                entries.append((pending_start, codepoint, pending_category))
                pending_start = None
                continue
            entries.append((codepoint, codepoint, category))
    entries.sort()
    runs = []
    for start, end, category in entries:
        if runs and runs[-1][1] + 1 == start and runs[-1][2] == category:
            runs[-1] = (runs[-1][0], end, category)
        else:
            runs.append((start, end, category))
    # Unassigned codepoints are Cn; drop explicit Cn runs to keep the table
    # small and let lookups default to Cn.
    return [run for run in runs if run[2] != "Cn"]


def parse_blocks(path):
    blocks = []
    with open(path, encoding="utf-8") as handle:
        for line in handle:
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            span, name = line.split(";", 1)
            start, end = span.split("..")
            normalized = name.strip().replace(" ", "")
            blocks.append((normalized, int(start, 16), int(end, 16)))
    return blocks


def emit(runs, blocks, output):
    with open(output, "w", encoding="utf-8") as out:
        out.write("//! Generated by tools/gen_unicode_categories.py from\n")
        out.write("//! UnicodeData.txt and Blocks.txt (Unicode 15.0.0).\n")
        out.write("//! Do not edit by hand.\n\n")
        out.write("pub const Category = enum(u8) {\n")
        for code in CATEGORY_CODES:
            out.write(f"    {code.lower()},\n")
        out.write("};\n\n")
        out.write("pub const Range = struct {\n")
        out.write("    start: u21,\n")
        out.write("    end: u21,\n")
        out.write("    category: Category,\n")
        out.write("};\n\n")
        out.write("/// Sorted, non-overlapping ranges of assigned codepoints.\n")
        out.write("/// Codepoints not listed here have category Cn.\n")
        out.write("pub const ranges = [_]Range{\n")
        for start, end, category in runs:
            out.write(
                f"    .{{ .start = 0x{start:04X}, .end = 0x{end:04X}, "
                f".category = .{category.lower()} }},\n"
            )
        out.write("};\n\n")
        out.write("pub const Block = struct {\n")
        out.write("    name: []const u8,\n")
        out.write("    start: u21,\n")
        out.write("    end: u21,\n")
        out.write("};\n\n")
        out.write("/// Sorted by name; block names have spaces removed.\n")
        out.write("pub const blocks = [_]Block{\n")
        by_name = {name: (start, end) for name, start, end in blocks}
        entries = [(name, start, end) for name, start, end in blocks]
        for alias, canonical in BLOCK_ALIASES.items():
            if alias in by_name or canonical not in by_name:
                continue
            start, end = by_name[canonical]
            entries.append((alias, start, end))
        entries.sort()
        for name, start, end in entries:
            out.write(
                f'    .{{ .name = "{name}", .start = 0x{start:04X}, '
                f".end = 0x{end:04X} }},\n"
            )
        out.write("};\n")


def main():
    data_dir = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/unicode"
    output = sys.argv[2] if len(sys.argv) > 2 else "src/xsd/unicode_categories.zig"
    runs = parse_unicode_data(os.path.join(data_dir, "UnicodeData.txt"))
    blocks = parse_blocks(os.path.join(data_dir, "Blocks.txt"))
    emit(runs, blocks, output)
    print(f"wrote {output}: {len(runs)} ranges, {len(blocks)} blocks")


if __name__ == "__main__":
    main()
